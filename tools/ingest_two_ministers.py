def clean_wikitext(t):
    t = re.sub(r"<ref[^>]*/>", "", t)          # өөрөө хаалттай ref
    t = re.sub(r"<ref[^>]*>.*?</ref>", "", t, flags=re.S)
    t = re.sub(r"\{\{[Ii]nfobox.*?\}\}", "", t, flags=re.S)
    t = re.sub(r"\{\{[^{}]*\}\}", "", t)
    t = re.sub(r"\[\[(?:[^|\]]*\|)?([^\]]+)\]\]", r"\1", t)
    t = re.sub(r"'''?", "", t)
    t = re.sub(r"^\[\[Ангилал:.*$", "", t, flags=re.M)
    t = re.sub(r"^\[\[.*$", "", t, flags=re.M)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


