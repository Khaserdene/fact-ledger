def get_or_create_entity(db, name, entity_type, description, tldr, aliases=None):
    ent = db.query(models.Entity).filter(models.Entity.name == name).first()
    if not ent:
        ent = models.Entity(
            name=name,
            entity_type=entity_type,
            description=description,
            tldr_summary=tldr,
            is_stub=False
        )
        db.add(ent)
        db.flush()
        print(f"Created Entity [{ent.id}] {name} ({entity_type})")
        if aliases:
            for al, kd in aliases:
                norm = al.lower().strip()
                existing_alias = db.query(models.EntityAlias).filter(
                    models.EntityAlias.entity_id == ent.id,
                    models.EntityAlias.alias_norm == norm
                ).first()
                if not existing_alias:
                    db.add(models.EntityAlias(entity_id=ent.id, alias=al, alias_norm=norm, kind=kd))
            db.flush()
    else:
        # update entity type if it was generic
        if ent.entity_type in ["org", "other"] and entity_type in ["government", "parliament", "state"]:
            ent.entity_type = entity_type
            db.flush()
        print(f"Using Existing Entity [{ent.id}] {name}")
    return ent


def get_or_create_relationship(db, source_ent, target_ent, rel_type, target_kind=None, source_id=None, quote=None):
    existing = db.query(models.Relationship).filter(
        models.Relationship.source_entity_id == source_ent.id,
        models.Relationship.target_entity_id == target_ent.id,
        models.Relationship.rel_type == rel_type
    ).first()
    if not existing:
        rel = models.Relationship(
            source_entity_id=source_ent.id,
            target_entity_id=target_ent.id,
            target_name=target_ent.name,
            rel_type=rel_type,
            target_kind=target_kind or target_ent.entity_type,
            source_id=source_id,
            source_quote=quote
        )
        db.add(rel)
        db.flush()
        return rel
    return existing


