def ingest_budgets():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()

    print(f"Connecting to {DB_PATH}")

    total_facts = 0
    updated_entities = 0

    for cab in CABINET_DATA:
        cid = cab["id"]
        cname = cab["name"]

        # Check entity exists
        row = c.execute("SELECT id, name FROM entities WHERE id = ?", (cid,)).fetchone()
        if not row:
            print(f"! Entity ID {cid} ({cname}) not found, skipping.")
            continue

        # 1. Update description & tldr
        c.execute("""
            UPDATE entities 
            SET description = ?, tldr_summary = ?
            WHERE id = ?
        """, (cab["description"], cab["tldr"], cid))
        updated_entities += 1

        # Lookup official source IDs
        nso_row = c.execute("SELECT id FROM sources WHERE url LIKE '%1212.mn%'").fetchone()
        gov_row = c.execute("SELECT id FROM sources WHERE url LIKE '%zasag.mn%'").fetchone()
        nso_source_id = nso_row[0] if nso_row else None
        gov_source_id = gov_row[0] if gov_row else None

        # 2. Insert Budget Facts
        for bdate, bval, btext in cab["budgets"]:
            # Check duplicate
            exists = c.execute("""
                SELECT id FROM facts WHERE entity_id = ? AND fact_text = ?
            """, (cid, btext)).fetchone()

            if not exists:
                tags = json.dumps(["улсын_төсөв", "санхүү", "засгийн_газар"], ensure_ascii=False)
                c.execute("""
                    INSERT INTO facts (
                        entity_id, fact_type, fact_date, date_precision,
                        fact_text, source_quote, role_context, topic, tags, source_id, created_at
                    ) VALUES (?, 'chronological', ?, 'year', ?, ?, ?, 'улсын_төсөв', ?, ?, CURRENT_TIMESTAMP)
                """, (cid, bdate, btext, btext, f"Улсын төсөв: {bval} тэрбум/их наяд ₮", tags, nso_source_id))
                fid = c.lastrowid
                c.execute("UPDATE facts SET fact_id = ? WHERE id = ?", (f"F{fid}", fid))
                total_facts += 1

        # 3. Insert Governance/Economic Facts
        for fdate, ftext, frole, ftags in cab["facts"]:
            exists = c.execute("""
                SELECT id FROM facts WHERE entity_id = ? AND fact_text = ?
            """, (cid, ftext)).fetchone()

            if not exists:
                tags = json.dumps(ftags + ["засгийн_газар"], ensure_ascii=False)
                c.execute("""
                    INSERT INTO facts (
                        entity_id, fact_type, fact_date, date_precision,
                        fact_text, source_quote, role_context, topic, tags, source_id, created_at
                    ) VALUES (?, 'chronological', ?, 'year', ?, ?, ?, 'засаглал', ?, ?, CURRENT_TIMESTAMP)
                """, (cid, fdate, ftext, ftext, frole, tags, gov_source_id))
                fid = c.lastrowid
                c.execute("UPDATE facts SET fact_id = ? WHERE id = ?", (f"F{fid}", fid))
                total_facts += 1

        print(f"✓ Ingested data for ID {cid}: {cname}")

    conn.commit()
    conn.close()
    print(f"\nSuccessfully updated {updated_entities} cabinets and inserted {total_facts} rich facts!")

if __name__ == "__main__":
    ingest_budgets()
