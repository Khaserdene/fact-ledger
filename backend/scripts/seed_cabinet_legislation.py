def seed_legislation_facts():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()

    # 1. Албан эх сурвалж үүсгэх
    legalinfo_source = get_or_create_source(
        db,
        title="Монгол Улсын Хууль тогтоомжийн нэгдсэн систем (Legalinfo.mn) & УИХ-ын цахим архив (1990–2024 он)",
        url="https://legalinfo.mn/mn/detail/laws",
        category="government",
        cleaned_text="Монгол Улсын Их Хурал, Засгийн газраас 1990 оноос хойш баталсан, өргөн мэдүүлсэн суурь хууль тогтоомжууд, Үндсэн хуулийн нэмэлт өөрчлөлтүүд, томоохон хөрөнгө оруулалтын гэрээнүүд болон УИХ дээр буцаагдсан хуулийн төслүүдийн албан ёсны цахим бүртгэл.",
        author="УИХ-ын Тамгын газар / Хууль зүйн үндэсний хүрээлэн"
    )

    total_inserted = 0
    total_skipped = 0

    for item in CABINET_LEGISLATION:
        cid = item["cabinet_id"]
        cab = db.query(models.Entity).filter(models.Entity.id == cid).first()
        if not cab:
            print(f"Cabinet entity [{cid}] not found, skipping...")
            continue

        for fact_date_str, fact_text, quote, tags, topic in item["laws"]:
            # Огноо хөрвүүлэх
            yr, mo, dy = [int(x) for x in fact_date_str.split("-")]
            f_date = date(yr, mo, dy)

            # Давхардал шалгах (тухайн субъект дээр ижил огноо, сэдэвтэй баримт)
            existing = db.query(models.Fact).filter(
                models.Fact.entity_id == cid,
                models.Fact.fact_date == f_date,
                models.Fact.topic == topic
            ).first()

            if not existing:
                fact = models.Fact(
                    entity_id=cid,
                    source_id=legalinfo_source.id,
                    fact_type="chronological",  # STRICT RULE: ONLY chronological or biographical
                    fact_date=f_date,
                    date_precision="day",
                    fact_text=fact_text,
                    source_quote=quote,
                    role_context="Хууль тогтоомж",
                    topic=topic,
                    stance="батлагдсан" if "батлагдсан" in tags else "унасан",
                    sentiment_score=0.5 if "батлагдсан" in tags else -0.5
                )
                fact.tags = tags
                db.add(fact)
                total_inserted += 1
            else:
                total_skipped += 1

    db.commit()
    print(f"Legislation seeding completed! Inserted: {total_inserted}, Skipped/Existing: {total_skipped}")

    # Засгийн газруудын баримтын шинэ тоог шалгах
    total_facts = db.query(func.count(models.Fact.id)).scalar()
    print(f"Total facts in DB: {total_facts}")


if __name__ == "__main__":
    seed_legislation_facts()
